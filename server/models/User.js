
// =========================================================
// User Model
// =========================================================

const mongoose =
    require("mongoose");


// =========================================================
// User Schema
// =========================================================

const userSchema =
    new mongoose.Schema({

        // =====================================================
        // Username
        // =====================================================

        username: {

            type:
                String,

            required:
                true,

            unique:
                true,

            trim:
                true

        },


        // =====================================================
        // Password
        // =====================================================

        password: {

            type:
                String,

            required:
                true

        }

    });


// =========================================================
// Export User Model
// =========================================================

module.exports =
    mongoose.model(
        "User",
        userSchema
    );